    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        String q=jTextField1.getText().trim().toLowerCase();DefaultTableModel m=(DefaultTableModel)jTable1.getModel();m.setRowCount(0);for(User u:userDAO.getByRole("Staff"))if(q.isEmpty()||u.getIdNumber().toLowerCase().contains(q)||u.getFullName().toLowerCase().contains(q)||u.getStatus().toLowerCase().contains(q))m.addRow(new Object[]{u.getIdNumber(),u.getFullName(),u.getRole(),u.getStatus()});
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int row=jTable1.getSelectedRow();if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Select a staff account first.");return;}String id=String.valueOf(jTable1.getValueAt(row,0));if(javax.swing.JOptionPane.showConfirmDialog(this,"Remove staff account "+id+"?","Confirm",javax.swing.JOptionPane.YES_NO_OPTION)==javax.swing.JOptionPane.YES_OPTION){if(userDAO.deleteStaff(id)){javax.swing.JOptionPane.showMessageDialog(this,"Staff account removed.");loadUsers();}else javax.swing.JOptionPane.showMessageDialog(this,"Unable to remove staff account.");}
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
        int row=jTable1.getSelectedRow();if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Select a staff account first.");return;}String id=String.valueOf(jTable1.getValueAt(row,0));String password=javax.swing.JOptionPane.showInputDialog(this,"Enter a new temporary password:");if(password!=null&&!password.isBlank()){if(userDAO.resetPassword(id,password))javax.swing.JOptionPane.showMessageDialog(this,"Password updated.");else javax.swing.JOptionPane.showMessageDialog(this,"Password update failed.");}
    }//GEN-LAST:event_jButton5ActionPerformed

