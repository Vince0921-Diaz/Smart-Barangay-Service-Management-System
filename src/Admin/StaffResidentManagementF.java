    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        String id = nextStaffId();
        String name=javax.swing.JOptionPane.showInputDialog(this,"Staff full name:");if(name==null||name.trim().isEmpty())return;
        String password=javax.swing.JOptionPane.showInputDialog(this,"Temporary password:");if(password==null||password.isEmpty())return;
        if(userDAO.addStaff(id,name.trim(),password)){javax.swing.JOptionPane.showMessageDialog(this,"Staff account added. Staff ID: "+id);loadUsers();}
        else javax.swing.JOptionPane.showMessageDialog(this,"Could not add staff. Check whether the ID already exists.");
    }//GEN-LAST:event_jButton2ActionPerformed

