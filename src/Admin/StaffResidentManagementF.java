    private String nextStaffId() {
        int max = 0;
        for (User user : userDAO.getByRole("Staff")) {
            String id = user.getIdNumber() == null ? "" : user.getIdNumber().trim().toUpperCase(java.util.Locale.ROOT);
            if (id.matches("STF\\d+")) {
                try { max = Math.max(max, Integer.parseInt(id.substring(3))); }
                catch (NumberFormatException ignored) { }
            }
        }
        return String.format(java.util.Locale.ROOT, "STF%03d", max + 1);
    }

    private void loadUsers(){DefaultTableModel m=(DefaultTableModel)jTable1.getModel();m.setRowCount(0);for(User u:userDAO.getByRole("Staff"))m.addRow(new Object[]{u.getIdNumber(),u.getFullName(),u.getRole(),u.getStatus()});}


