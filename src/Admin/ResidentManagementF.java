    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a resident to delete.");
            return;
        }

        String id = Model.getValueAt(selectedRow, 0).toString();
        int confirm = JOptionPane.showConfirmDialog(
                this,
                "Are you sure you want to delete resident " + id + "?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION
        );

        if (confirm == JOptionPane.YES_OPTION) {
            if (residentDAO.deleteResident(id)) {
                JOptionPane.showMessageDialog(this, "Resident deleted successfully!");
                loadResidents();
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this, "Failed to delete resident.");
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

