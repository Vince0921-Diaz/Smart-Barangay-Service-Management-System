    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        // TODO add your handling code here:
        String search = txtSearch.getText().trim().toLowerCase();

    if (search.isEmpty() || search.equals("search")) {

        JOptionPane.showMessageDialog(
                this,
                "Please enter a name or ID to search."
        );

        return;
    }

    for (int i = 0; i < Model.getRowCount(); i++) {

        String id = Model.getValueAt(i, 0).toString().toLowerCase();
        String name = (Model.getValueAt(i, 1).toString() + " " + Model.getValueAt(i, 3).toString() + " " + Model.getValueAt(i, 2).toString()).toLowerCase();

        if (id.equals(search) || name.contains(search)) {

            jTable1.setRowSelectionInterval(i, i);

            jTable1.scrollRectToVisible(
                    jTable1.getCellRect(i, 0, true)
            );

            showPersonalDetails(i);

            return;
        }
    }

    JOptionPane.showMessageDialog(
            this,
            "Resident not found."
    );

    }//GEN-LAST:event_btnViewActionPerformed

