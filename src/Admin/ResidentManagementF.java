    private void updateResidentStatus(String status) {
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            JOptionPane.showMessageDialog(this, "Select a resident first.");
            return;
        }
        String id = String.valueOf(Model.getValueAt(row, 0));
        if (residentDAO.updateStatus(id, status) && new dao.UserDAO().setStatus(id, status)) {
            if ("Approved".equalsIgnoreCase(status)) {
                if (id.startsWith("REG-")) {
                    JOptionPane.showMessageDialog(this, "Registration approved successfully. A permanent Resident ID has been assigned. Check the refreshed resident list for the new ID.", "Resident Approved", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Resident approved successfully.\nResident ID: " + id + "\nPlease provide this ID to the resident so they can log in.", "Resident Approved", JOptionPane.INFORMATION_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Resident " + status.toLowerCase() + " successfully.");
            }
            loadResidents();
            clearFields();
        } else {
            JOptionPane.showMessageDialog(this, "Could not update resident status. Check that the resident account exists.");
        }
    }

    private void loadResidents() {
        Model.setRowCount(0);
        for (Resident resident : residentDAO.getAllResidents()) {
            Model.addRow(new Object[]{resident.getIdNumber(), resident.getFirstName(), resident.getMiddleName(), resident.getLastName(), resident.getGender(), resident.getAge(), resident.getAddress(), resident.getContactNumber(), resident.getGovernmentIdType(), resident.getDisability(), resident.getStatus()});
        }
    }

    private void showPersonalDetails(int row) {
        if (row < 0 || row >= Model.getRowCount()) return;
        String id = String.valueOf(Model.getValueAt(row, 0));
        Resident resident = residentDAO.findResident(id);
        if (resident == null) return;
        txtIDNumber.setText(resident.getIdNumber());
        txtFirstName.setText(resident.getFirstName());
        txtLastName.setText(resident.getLastName());
        txtGender.setText(resident.getMiddleName());
        txtGender1.setText(resident.getGender());
        txtGender2.setText(String.valueOf(resident.getAge()));
        txtAddress.setText(resident.getAddress());
        txtAge1.setText(resident.getContactNumber());
        txtAge2.setText(resident.getGovernmentIdType());
        txtAge3.setText(resident.getDisability());
        jLabel14.setText("Status: " + resident.getStatus());
    }

    private void clearFields() {
        txtIDNumber.setText(""); txtFirstName.setText(""); txtLastName.setText("");
        txtGender.setText(""); txtGender1.setText(""); txtGender2.setText("");
        txtAge1.setText(""); txtAge2.setText(""); txtAge3.setText("");
        jLabel14.setText("Status:");
        jTable1.clearSelection();
    }

