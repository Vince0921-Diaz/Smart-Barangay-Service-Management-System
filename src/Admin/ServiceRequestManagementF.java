    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int row = jTable1.getSelectedRow();
        if (row < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Select a request first.");
            return;
        }
        int modelRow = jTable1.convertRowIndexToModel(row);
        int id = Integer.parseInt(String.valueOf(jTable1.getModel().getValueAt(modelRow, 0)));
        model.ServiceRequest selected = null;
        for (model.ServiceRequest item : requestDAO.getAll()) {
            if (item.getId() == id) { selected = item; break; }
        }
        if (selected == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Request not found. Refresh the list.");
            loadRequests();
            return;
        }
        javax.swing.JOptionPane.showMessageDialog(this,
            "Request ID: " + selected.getId() + "\nResident: " + selected.getResidentName() +
            "\nService: " + selected.getServiceName() + "\nPurpose: " + selected.getPurpose() +
            "\nFee: PHP " + String.format("%.2f", selected.getFee()) + "\nStatus: " + selected.getStatus(),
            "Request Details", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_jButton1ActionPerformed

