    private String priorityFor(ServiceRequest r) {
        model.Resident resident = new dao.ResidentDAO().findById(r.getResidentId());
        if (resident == null) return "Regular";
        String disability = resident.getDisability() == null ? "" : resident.getDisability().toLowerCase(java.util.Locale.ROOT);
        if (disability.contains("pwd") || disability.contains("disab")) return "PWD";
        if (resident.getAge() >= 60) return "Senior";
        try {
            java.sql.Connection c = database.DatabaseConnection.getConnection();
            try (java.sql.PreparedStatement ps = c.prepareStatement("SELECT is_pregnant FROM residents WHERE id_number=?")) {
                ps.setString(1, r.getResidentId());
                try (java.sql.ResultSet rs = ps.executeQuery()) {
                    if (rs.next() && rs.getBoolean(1)) return "Pregnant";
                }
            } finally { c.close(); }
        } catch (java.sql.SQLException ex) { ex.printStackTrace(); }
        return "Regular";
    }
    private Object[] rowFor(ServiceRequest r) {
        String raw = r.getDateTime() == null ? "" : r.getDateTime();
        String date = raw, time = "";
        if (raw.contains(" ")) { String[] parts = raw.split(" ", 2); date = parts[0]; time = parts[1]; }
        try {
            if (!time.isBlank()) time = java.time.LocalTime.parse(time.length() >= 8 ? time.substring(0,8) : time)
                .format(java.time.format.DateTimeFormatter.ofPattern("h:mm a", java.util.Locale.US));
        } catch (Exception ignored) { }
        return new Object[]{String.format(java.util.Locale.ROOT, "%03d", r.getId()), r.getResidentName(), r.getServiceName(), priorityFor(r), date, time, r.getStatus()};
    }
    private void loadRequests() {
        DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
        m.setRowCount(0);
        java.util.List<ServiceRequest> requests = requestDAO.getAll();
        requests.sort(java.util.Comparator
            .comparingInt((ServiceRequest r) -> {
                String p = priorityFor(r);
                return "PWD".equals(p) ? 0 : "Pregnant".equals(p) ? 1 : "Senior".equals(p) ? 2 : 3;
            })
            .thenComparing(ServiceRequest::getDateTime, java.util.Comparator.nullsLast(java.util.Comparator.naturalOrder())));
        for (ServiceRequest r : requests) m.addRow(rowFor(r));
    }


