    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int row=jTable1.getSelectedRow(); if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Select a service first.");return;}
        Service x=serviceDAO.findByName(String.valueOf(jTable1.getValueAt(row,0))); if(x==null)return;
        if(javax.swing.JOptionPane.showConfirmDialog(this,"Delete "+x.getName()+"?","Confirm",javax.swing.JOptionPane.YES_NO_OPTION)==javax.swing.JOptionPane.YES_OPTION){boolean ok=serviceDAO.delete(x.getId());javax.swing.JOptionPane.showMessageDialog(this,ok?"Service deleted.":"Cannot delete a service already used by requests.");loadServices();}
    }//GEN-LAST:event_jButton3ActionPerformed

