    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int row=jTable1.getSelectedRow(); if(row<0){javax.swing.JOptionPane.showMessageDialog(this,"Select a service first.");return;}
        Service x=serviceDAO.findByName(String.valueOf(jTable1.getValueAt(row,0))); if(x==null)return;
        String name=javax.swing.JOptionPane.showInputDialog(this,"Service name:",x.getName()); if(name==null)return;
        String cat=javax.swing.JOptionPane.showInputDialog(this,"Category:",x.getCategory()); if(cat==null)return;
        String desc=javax.swing.JOptionPane.showInputDialog(this,"Description:",x.getDescription()); if(desc==null)return;
        String feeText=javax.swing.JOptionPane.showInputDialog(this,"Fee:",String.valueOf(x.getFee())); if(feeText==null)return;
        double fee;try{fee=Double.parseDouble(feeText);}catch(Exception e){javax.swing.JOptionPane.showMessageDialog(this,"Invalid fee.");return;}
        boolean ok=serviceDAO.update(x.getId(),name.trim(),cat.trim(),desc.trim(),fee,x.getStatus()); javax.swing.JOptionPane.showMessageDialog(this,ok?"Service updated.":"Update failed."); loadServices();
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String name=javax.swing.JOptionPane.showInputDialog(this,"Service name:"); if(name==null||name.isBlank())return;
        String category=javax.swing.JOptionPane.showInputDialog(this,"Category:"); if(category==null||category.isBlank())return;
        String desc=javax.swing.JOptionPane.showInputDialog(this,"Description:"); if(desc==null)desc="";
        String feeText=javax.swing.JOptionPane.showInputDialog(this,"Fee:","150"); double fee; try{fee=Double.parseDouble(feeText);}catch(Exception e){javax.swing.JOptionPane.showMessageDialog(this,"Invalid fee.");return;}
        boolean ok=serviceDAO.add(name.trim(),category.trim(),desc.trim(),fee,"Active"); javax.swing.JOptionPane.showMessageDialog(this,ok?"Service added.":"Unable to add service."); loadServices();
    }//GEN-LAST:event_jButton1ActionPerformed

