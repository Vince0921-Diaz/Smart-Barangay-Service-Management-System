    private long todayAppointmentCount() {
        String today = java.time.LocalDate.now().toString();
        return new dao.AppoinmentDAO().getAll().stream()
            .filter(a -> a.getDate() != null && today.equals(a.getDate()))
            .count();
    }
    private void loadResidents(){DefaultTableModel m=(DefaultTableModel)jTable1.getModel();m.setRowCount(0);for(Resident r:residentDAO.getAllResidents())m.addRow(new Object[]{r.getIdNumber(),r.getFirstName(),r.getLastName(),r.getMiddleName(),r.getGender(),r.getAge(),r.getAddress(),r.getContactNumber(),r.getGovernmentIdType(),r.getDisability(),r.getStatus()});}


    private void filterResidents() {
        String q = jTextField1.getText().trim().toLowerCase(java.util.Locale.ROOT);
        DefaultTableModel m = (DefaultTableModel) jTable1.getModel();
        m.setRowCount(0);
        for (model.Resident r : residentDAO.getAllResidents()) {
            if (q.isEmpty() || r.getIdNumber().toLowerCase(java.util.Locale.ROOT).contains(q)
                    || r.getFullName().toLowerCase(java.util.Locale.ROOT).contains(q)
                    || r.getAddress().toLowerCase(java.util.Locale.ROOT).contains(q)
                    || r.getStatus().toLowerCase(java.util.Locale.ROOT).contains(q)) {
                m.addRow(new Object[]{r.getIdNumber(),r.getFirstName(),r.getLastName(),r.getMiddleName(),r.getGender(),r.getAge(),r.getAddress(),r.getContactNumber(),r.getGovernmentIdType(),r.getDisability(),r.getStatus()});
            }
        }
    }


