    private void loadReportsAsync(){
        javax.swing.SwingWorker<Object[],Void> worker = new javax.swing.SwingWorker<>() {
            @Override protected Object[] doInBackground() {
                long total=requestDAO.count(null);
                long appointments=appointmentDAO.getAll().size();
                long pending=requestDAO.count("Pending");
                long approved=requestDAO.count("Approved");
                java.util.List<Object[]> rows=new java.util.ArrayList<>();
                for(String st:new String[]{"Pending","Approved","Rejected"}) rows.add(new Object[]{st,requestDAO.count(st)});
                return new Object[]{total,appointments,pending,approved,rows};
            }
            @Override protected void done(){
                try{
                    Object[] d=get();
                    jLabel2.setText(String.valueOf(d[0])); jLabel3.setText(String.valueOf(d[1])); jLabel4.setText(String.valueOf(d[2])); jLabel6.setText(String.valueOf(d[3]));
                    DefaultTableModel m=(DefaultTableModel)jTable1.getModel(); m.setRowCount(0); for(Object[] row:(java.util.List<Object[]>)d[4]) m.addRow(row);
                }catch(Exception ex){ex.printStackTrace();javax.swing.JOptionPane.showMessageDialog(StaffReportsF.this,"Unable to load reports. Please check that MySQL is running.","Reports Error",javax.swing.JOptionPane.ERROR_MESSAGE);}
            }
        };
        worker.execute();
    }



