    private Object[] staffRow(ServiceRequest r) {
        String raw = r.getDateTime() == null ? "" : r.getDateTime();
        String date = raw, time = "";
        if (raw.contains(" ")) { String[] parts = raw.split(" ", 2); date = parts[0]; time = parts[1]; }
        try { if (!time.isBlank()) time = java.time.LocalTime.parse(time.length() >= 8 ? time.substring(0,8) : time).format(java.time.format.DateTimeFormatter.ofPattern("h:mm a", java.util.Locale.US)); } catch (Exception ignored) {}
        String priority = "Regular";
        model.Resident resident = new dao.ResidentDAO().findById(r.getResidentId());
        if (resident != null) {
            String d = resident.getDisability() == null ? "" : resident.getDisability().toLowerCase(java.util.Locale.ROOT);
            if (d.contains("pwd") || d.contains("disab")) priority = "PWD";
            else if (resident.getAge() >= 60) priority = "Senior";
            else {
                try (java.sql.Connection c = database.DatabaseConnection.getConnection();
                     java.sql.PreparedStatement ps = c.prepareStatement("SELECT is_pregnant FROM residents WHERE id_number=?")) {
                    ps.setString(1, r.getResidentId());
                    try (java.sql.ResultSet rs = ps.executeQuery()) { if (rs.next() && rs.getBoolean(1)) priority = "Pregnant"; }
                } catch (java.sql.SQLException ex) { ex.printStackTrace(); }
            }
        }
        return new Object[]{String.format(java.util.Locale.ROOT, "%03d", r.getId()), r.getResidentName(), r.getServiceName(), priority, date, time, r.getStatus()};
    }

    private void loadRequests(){
        java.util.List<ServiceRequest> requests=requestDAO.getAll();
        DefaultTableModel m=(DefaultTableModel)jTable2.getModel();
        m.setRowCount(0);
        for(ServiceRequest r:requests){
            m.addRow(staffRow(r));
        }
        jLabel4.setText(String.valueOf(requestDAO.count(null)));
        jLabel5.setText(String.valueOf(requestDAO.count("Pending")));
        jLabel3.setText(String.valueOf(requestDAO.count("Rejected")));
        jLabel6.setText(String.valueOf(requestDAO.count("Approved")));
    }


    private void filterRequests() {
        String q = jTextField1.getText().trim().toLowerCase(java.util.Locale.ROOT);
        DefaultTableModel m = (DefaultTableModel) jTable2.getModel();
        m.setRowCount(0);
        for (ServiceRequest r : requestDAO.getAll()) {
            if (q.isEmpty() || String.format(java.util.Locale.ROOT, "%03d", r.getId()).equals(q)
                    || r.getResidentName().toLowerCase(java.util.Locale.ROOT).contains(q)
                    || r.getServiceName().toLowerCase(java.util.Locale.ROOT).contains(q)
                    || r.getStatus().toLowerCase(java.util.Locale.ROOT).contains(q)) {
                m.addRow(staffRow(r));
            }
        }
    }


