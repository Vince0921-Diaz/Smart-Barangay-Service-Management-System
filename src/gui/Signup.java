    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {
        String first = jTextField1.getText().trim();
        String last = jTextField2.getText().trim();
        String middle = jTextField3.getText().trim();
        String ageText = jTextField5.getText().trim();
        String contact = jTextField6.getText().trim();
        String gender = String.valueOf(jComboBox4.getSelectedItem()).trim();
        String address = String.valueOf(jComboBox1.getSelectedItem()).trim();
        String idType = String.valueOf(jComboBox2.getSelectedItem()).trim();
        String disability = String.valueOf(jComboBox3.getSelectedItem()).trim();
        String password = new String(jPasswordField1.getPassword());
        String confirm = new String(jPasswordField2.getPassword());

        if (first.isEmpty() || first.equalsIgnoreCase("First Name") || last.isEmpty() || last.equalsIgnoreCase("Last Name") || ageText.isEmpty() || ageText.equalsIgnoreCase("Age") || contact.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter your first name, last name, age, and contact number.", "Incomplete Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (gender.equals("Select Gender") || gender.isBlank() || address.startsWith("Select") || idType.startsWith("Select") || disability.startsWith("Select")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select your gender, address, ID type, and disability status.", "Incomplete Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!first.matches("[\\p{L} .'-]{1,100}") || !last.matches("[\\p{L} .'-]{1,100}") || (!middle.isEmpty() && !middle.matches("[\\p{L} .'-]{1,100}"))) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter valid names.", "Invalid Name", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!contact.matches("[0-9+() -]{7,20}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid contact number.", "Invalid Contact Number", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        int age;
        try {
            age = Integer.parseInt(ageText);
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Age must be a number.", "Invalid Age", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (age < 18 || age > 120) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid age between 18 and 120.", "Invalid Age", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!jCheckBox2.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please confirm that you will present your original valid ID to the Barangay Office.", "Confirmation Required", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (password.isBlank() || confirm.isBlank()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter and confirm your password.", "Password Required", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (password.length() < 8 || !password.matches(".*[A-Za-z].*") || !password.matches(".*[0-9].*") || !password.matches(".*[^A-Za-z0-9].*")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Password must be at least 8 characters and contain a letter, number, and symbol.", "Invalid Password", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!password.equals(confirm)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Passwords do not match.", "Password Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        ResidentDAO residentDAO = new ResidentDAO();
        UserDAO userDAO = new UserDAO();
        Resident candidate = new Resident(null, first, middle, last, gender, age, address, idType, contact, disability, true, "Pending");

        // If the entered details match an already-approved barangay record, reuse that ID.
        Resident existing = residentDAO.findMatchingApprovedRecord(candidate);
        if (existing != null) {
            if (residentDAO.hasUserAccount(existing.getIdNumber())) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "A login account already exists for this resident record. Please log in or use password recovery.",
                    "Account Already Exists", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }
            if (!userDAO.createUser(existing.getIdNumber(), existing.getFullName(), password, "Approved")) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Could not create the account for the existing resident record. Check the database connection and try again.",
                    "Registration Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }
            javax.swing.JOptionPane.showMessageDialog(this,
                "Existing barangay record verified. Your account is active.\nYour Resident ID is " + existing.getIdNumber() + ". You can now log in.",
                "Registration Successful", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            Login login = new Login(); login.setLocationRelativeTo(null); login.setVisible(true); dispose();
            return;
        }

        // New residents receive an internal registration key only. A public numeric Resident ID
        // is allocated later, inside the admin approval transaction.
        String registrationKey = "REG-" + java.util.UUID.randomUUID().toString().replace("-", "").substring(0, 16).toUpperCase(java.util.Locale.ROOT);
        candidate.setIdNumber(registrationKey);
        candidate.setStatus("Pending");
        String createdId = residentDAO.addResident(candidate);
        if (createdId == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Could not save your registration. Check the database connection and try again.", "Registration Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (!userDAO.createUser(createdId, candidate.getFullName(), password, "Pending")) {
            residentDAO.deleteResident(createdId);
            javax.swing.JOptionPane.showMessageDialog(this, "Could not create your registration account. Please try again.", "Registration Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
        javax.swing.JOptionPane.showMessageDialog(this,
            "Registration submitted successfully.\nYour details will be reviewed by the admin.\nA Resident ID will be assigned only after approval.",
            "Registration Submitted", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        Login login = new Login(); login.setLocationRelativeTo(null); login.setVisible(true); dispose();
    }

