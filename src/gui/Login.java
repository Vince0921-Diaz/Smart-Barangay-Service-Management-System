    private void forgotPassword() {
        javax.swing.JTextField idField = new javax.swing.JTextField(18);
        javax.swing.JTextField nameField = new javax.swing.JTextField(18);
        javax.swing.JPasswordField newPasswordField = new javax.swing.JPasswordField(18);
        javax.swing.JPasswordField confirmPasswordField = new javax.swing.JPasswordField(18);
        javax.swing.JPanel form = new javax.swing.JPanel(new java.awt.GridLayout(0, 1, 5, 5));
        form.add(new javax.swing.JLabel("Account ID number"));
        form.add(idField);
        form.add(new javax.swing.JLabel("Full name registered to the account"));
        form.add(nameField);
        form.add(new javax.swing.JLabel("New password (8+ characters, letter, number and symbol)"));
        form.add(newPasswordField);
        form.add(new javax.swing.JLabel("Confirm new password"));
        form.add(confirmPasswordField);
        int choice = javax.swing.JOptionPane.showConfirmDialog(this, form, "Reset Password", javax.swing.JOptionPane.OK_CANCEL_OPTION, javax.swing.JOptionPane.PLAIN_MESSAGE);
        if (choice != javax.swing.JOptionPane.OK_OPTION) return;
        String id = idField.getText().trim();
        String fullName = nameField.getText().trim();
        String newPassword = new String(newPasswordField.getPassword());
        String confirmPassword = new String(confirmPasswordField.getPassword());
        if (id.isEmpty() || fullName.isEmpty() || newPassword.isEmpty() || confirmPassword.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please complete all fields.", "Missing Information", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (newPassword.length() < 8 || !newPassword.matches(".*[A-Za-z].*") || !newPassword.matches(".*[0-9].*") || !newPassword.matches(".*[^A-Za-z0-9].*")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Use at least 8 characters with a letter, number and symbol.", "Invalid Password", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!newPassword.equals(confirmPassword)) {
            javax.swing.JOptionPane.showMessageDialog(this, "The passwords do not match.", "Password Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (new dao.UserDAO().resetPasswordVerified(id, fullName, newPassword)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Password reset successfully. You can now log in.", "Password Reset", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "The ID number and registered name do not match an account. Please check your details.", "Account Not Found", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }

    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {
        String idNumber = txtUsername.getText().trim();
        String password = new String(Password.getPassword());
        if (idNumber.isEmpty() || idNumber.equals("Username") || password.isEmpty() || password.equals("Password")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter your ID and password.");
            return;
        }
        // Classroom demo accounts retained from the existing project.
        if (idNumber.equalsIgnoreCase("ADM001") && password.equals("admin123!")) {
            Session.login("ADM001", "Administrator", "Admin");
            AdminDashboard nextScreen = new AdminDashboard(); nextScreen.setLocationRelativeTo(null); nextScreen.setVisible(true); this.dispose(); return;
        }
        // STF001 is authenticated through UserDAO like every other account.
        // Deleting or disabling this account in the database must prevent login.
        UserDAO userDAO = new UserDAO();
        User user = userDAO.authenticate(idNumber, password);
        if (user == null) {
            String dbError = UserDAO.getLastAuthenticationError();
            String message = (dbError == null || dbError.isBlank())
                ? "Invalid ID or password. If this is a database issue, verify that XAMPP MySQL is running and the MySQL Connector/J library is installed."
                : "Database login failed: " + dbError + "\nCheck XAMPP MySQL and the project's JDBC driver/configuration.";
            javax.swing.JOptionPane.showMessageDialog(this, message, "Login failed", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!"Approved".equalsIgnoreCase(user.getStatus())) {
            javax.swing.JOptionPane.showMessageDialog(this, "Your account is still " + user.getStatus() + ". Please wait for verification.");
            return;
        }
        Session.login(user.getIdNumber(), user.getFullName(), user.getRole());
        if ("Admin".equalsIgnoreCase(user.getRole()) || "Administrator".equalsIgnoreCase(user.getRole())) {
            new AdminDashboard().setVisible(true);
        } else if ("Staff".equalsIgnoreCase(user.getRole())) {
            new StaffDashboard().setVisible(true);
        } else {
            new ResidentDashboard().setVisible(true);
        }
        this.dispose();
    }                                        

