    private void cancelSelectedRequest() {
        int row = jTable1.getSelectedRow();
        if (row < 0) return;
        String status = String.valueOf(jTable1.getValueAt(row, 3));
        if (!"Pending".equalsIgnoreCase(status)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Only pending requests can be cancelled. Approved requests cannot be cancelled here.");
            return;
        }
        int id;
        try { id = Integer.parseInt(String.valueOf(jTable1.getValueAt(row, 0))); }
        catch (NumberFormatException ex) { return; }
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Cancel this pending service request and its appointment?", "Confirm Cancellation", javax.swing.JOptionPane.YES_NO_OPTION);
        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            if (requestDAO.cancelPending(id, util.Session.getUserId())) {
                javax.swing.JOptionPane.showMessageDialog(this, "Request and pending appointment cancelled.");
                loadRequests("All");
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Cancellation failed. The request may no longer be pending.");
            }
        }
    }                                        

