    private void loadRequests(String filter) {
        DefaultTableModel m=(DefaultTableModel)jTable1.getModel();
        m.setRowCount(0);
        if(!util.Session.isLoggedIn()) return;
        for (ServiceRequest r : requestDAO.getByResident(util.Session.getUserId())) {
            String status = r.getStatus() == null ? "" : r.getStatus().trim();
            if ("Cancelled".equalsIgnoreCase(status) || "Canceled".equalsIgnoreCase(status)) continue;
            String normalizedFilter = "Approve".equalsIgnoreCase(filter) ? "Approved" : filter;
            if (!normalizedFilter.equals("All") && !status.equalsIgnoreCase(normalizedFilter)) continue;
            String raw = r.getDateTime() == null ? "" : r.getDateTime();
            String date = raw, time = "";
            if (raw.contains(" ")) { String[] parts = raw.split(" ", 2); date = parts[0]; time = parts[1]; }
            try { if (!time.isBlank()) time = java.time.LocalTime.parse(time.length() >= 8 ? time.substring(0,8) : time).format(java.time.format.DateTimeFormatter.ofPattern("h:mm a", java.util.Locale.US)); } catch (Exception ignored) {}
            m.addRow(new Object[]{r.getId(), r.getServiceName(), date, time, String.format(java.util.Locale.US, "₱ %.2f", r.getFee()), status});
        }
    }

