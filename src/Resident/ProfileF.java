    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (resident == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Resident profile could not be loaded.");
            return;
        }
        int confirm=javax.swing.JOptionPane.showConfirmDialog(this,
                "Delete your resident account? This will also remove your service requests and appointments.",
                "Confirm Account Deletion", javax.swing.JOptionPane.YES_NO_OPTION);
        if(confirm==javax.swing.JOptionPane.YES_OPTION && residentDAO.deleteResident(resident.getIdNumber())){
            util.Session.clear();
            javax.swing.JOptionPane.showMessageDialog(this, "Account deleted successfully.");
            gui.Login nextScreen = new gui.Login(); nextScreen.setLocationRelativeTo(null); nextScreen.setVisible(true); this.dispose();
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

