    private void loadProfile(){
        if(!util.Session.isLoggedIn()) return;
        resident=residentDAO.findResident(util.Session.getUserId());
        if(resident==null) return;
        txtIDNumber.setText(resident.getIdNumber());
        txtFirstName.setText(resident.getFirstName());
        txtLastName.setText(resident.getLastName());
        txtGender.setText(resident.getMiddleName());
        txtGender1.setText(resident.getGender());
        txtGender2.setText(String.valueOf(resident.getAge()));
        txtAge.setText(resident.getAddress());
        txtAge1.setText(resident.getContactNumber());
        txtAge2.setText(resident.getGovernmentIdType());
        txtAge3.setText(resident.getDisability());
        jLabel14.setText("Status: " + resident.getStatus());
        setFieldsEnabled(false);
    }
    private void setFieldsEnabled(boolean enabled){
        // Only the resident's name, age, address and contact number are editable.
        txtFirstName.setEditable(enabled);
        txtLastName.setEditable(enabled);
        txtGender.setEditable(enabled); // Middle name
        txtGender2.setEditable(enabled); // Age
        txtAge.setEditable(enabled);     // Address
        txtAge1.setEditable(enabled);    // Contact number
        txtIDNumber.setEditable(false);
        txtGender1.setEditable(false);   // Gender
        txtAge2.setEditable(false);      // Government ID type
        txtAge3.setEditable(false);      // Disabilities
        txtIDNumber.setFocusable(false);
        txtGender1.setFocusable(false);
        txtAge2.setFocusable(false);
        txtAge3.setFocusable(false);
    }


