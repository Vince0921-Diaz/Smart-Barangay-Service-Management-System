    private void jButton24ActionPerformed(java.awt.event.ActionEvent evt) {
if (!util.Session.isLoggedIn() || !"Resident".equalsIgnoreCase(util.Session.getRole())) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please log in with an approved resident account before submitting a request.");
            return;
        }
        Object selected = jComboBox1.getSelectedItem();
        if (selected == null) { javax.swing.JOptionPane.showMessageDialog(this, "No active services are available."); return; }
        model.Service service = new dao.ServiceDAO().findByName(selected.toString());
        if (service == null) { javax.swing.JOptionPane.showMessageDialog(this, "The selected service could not be loaded. Refresh and try again."); return; }
        String purpose = jTextField5.getText().trim();
        if (purpose.isEmpty()) { javax.swing.JOptionPane.showMessageDialog(this, "Please enter the purpose of your request."); jTextField5.requestFocusInWindow(); return; }
        if (!jCheckBox1.isSelected()) { javax.swing.JOptionPane.showMessageDialog(this, "Please confirm that you agree to pay the required fee at the barangay office."); return; }
        String dateText = jTextField7.getText().trim();
        String timeText = jTextField3.getText().trim();
        if ("YYYY-MM-DD".equalsIgnoreCase(dateText)) dateText = "";
        if ("HH:MM AM/PM (e.g., 7:30 AM)".equalsIgnoreCase(timeText) && jTextField3.getForeground().equals(java.awt.Color.GRAY)) timeText = "";
        java.time.LocalDate date;
        try { date = java.time.LocalDate.parse(dateText); }
        catch (java.time.format.DateTimeParseException ex) { javax.swing.JOptionPane.showMessageDialog(this, "Enter the appointment date as YYYY-MM-DD."); jTextField7.requestFocusInWindow(); return; }
        if (!date.isAfter(java.time.LocalDate.now())) { javax.swing.JOptionPane.showMessageDialog(this, "Please choose a future appointment date."); return; }
        java.time.LocalTime time = parseAppointmentTime(timeText);
        if (time == null) { javax.swing.JOptionPane.showMessageDialog(this, "Enter time with AM/PM, for example 9:30 AM or 2:15 PM."); jTextField3.requestFocusInWindow(); return; }
        java.time.LocalTime open = java.time.LocalTime.of(7,30);
        java.time.LocalTime lunchStart = java.time.LocalTime.NOON;
        java.time.LocalTime lunchEnd = java.time.LocalTime.of(13,0);
        java.time.LocalTime close = java.time.LocalTime.of(17,0);
        if (time.isBefore(open) || time.isAfter(close)
                || (!time.isBefore(lunchStart) && time.isBefore(lunchEnd))) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Appointment hours are 7:30 AM–5:00 PM. Lunch break is 12:00 PM–1:00 PM.");
            jTextField3.requestFocusInWindow();
            return;
        }
        String normalizedTime = time.format(java.time.format.DateTimeFormatter.ofPattern("HH:mm:ss", java.util.Locale.US));
        int requestId = new dao.ServiceRequestDAO().addWithAppointment(util.Session.getUserId(), service.getId(), service.getFee(), purpose, date.toString(), normalizedTime);
        if (requestId > 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Service request and appointment submitted successfully.\nRequest ID: " + requestId + "\nAppointment: " + date + " at " + normalizedTime + "\nStatus: Pending");
            jTextField5.setText(""); jTextField7.setText(""); jTextField3.setText(""); jCheckBox1.setSelected(false);
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Could not submit the request. The selected appointment time may already be taken, or the database is unavailable. No request or appointment was saved.", "Submission failed", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }                                         

